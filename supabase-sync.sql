-- Run this script once in the Supabase SQL Editor for the Heartlink project.
-- It creates secure couple pairing, shared persistence, and private media storage.

create table if not exists public.couples (
  couple_code text primary key,
  user1_email text not null,
  user2_email text,
  constraint couples_user1_email_unique unique (user1_email),
  constraint couples_user2_email_unique unique (user2_email),
  constraint couples_distinct_members check (
    user2_email is null or lower(user1_email) <> lower(user2_email)
  )
);

create or replace function public.get_heartlink_couple()
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_email text := lower(auth.jwt() ->> 'email');
  current_code text;
begin
  if current_email is null then
    raise exception 'Sign in before checking couple pairing.';
  end if;

  select couple_code
    into current_code
    from public.couples
    where lower(user1_email) = current_email or lower(user2_email) = current_email
    limit 1;

  return current_code;
end;
$$;

create or replace function public.create_heartlink_couple(target_code text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_email text := lower(auth.jwt() ->> 'email');
  current_code text;
begin
  if current_email is null then
    raise exception 'Sign in before creating a couple code.';
  end if;
  if target_code !~ '^HL-[0-9]{4}$' then
    raise exception 'Couple code must use the format HL-1234.';
  end if;

  select couple_code
    into current_code
    from public.couples
    where lower(user1_email) = current_email or lower(user2_email) = current_email
    limit 1;

  if current_code is not null then
    return current_code;
  end if;

  insert into public.couples (couple_code, user1_email)
    values (target_code, current_email)
    on conflict (couple_code) do nothing
    returning couple_code into current_code;

  if current_code is null then
    raise exception 'That couple code is already in use. Generate another code and try again.';
  end if;

  return current_code;
end;
$$;

create or replace function public.join_heartlink_couple(target_code text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_email text := lower(auth.jwt() ->> 'email');
  joined_code text;
begin
  if current_email is null then
    raise exception 'Sign in before joining a couple.';
  end if;

  if exists (
    select 1
    from public.couples
    where lower(user1_email) = current_email or lower(user2_email) = current_email
  ) then
    raise exception 'This account is already paired.';
  end if;

  update public.couples
    set user2_email = current_email
    where couple_code = upper(trim(target_code))
      and user2_email is null
      and lower(user1_email) <> current_email
    returning couple_code into joined_code;

  if joined_code is null then
    raise exception 'Couple code not found or already paired.';
  end if;

  return joined_code;
end;
$$;

alter table public.couples enable row level security;
revoke all on public.couples from anon, authenticated;

revoke all on function public.get_heartlink_couple() from public;
revoke all on function public.create_heartlink_couple(text) from public;
revoke all on function public.join_heartlink_couple(text) from public;
grant execute on function public.get_heartlink_couple() to authenticated;
grant execute on function public.create_heartlink_couple(text) to authenticated;
grant execute on function public.join_heartlink_couple(text) to authenticated;

create table if not exists public.couple_app_data (
  id bigint generated by default as identity primary key,
  couple_code text not null,
  data_type text not null check (
    data_type in (
      'chat',
      'signal',
      'post',
      'song',
      'schedule',
      'settings',
      'wallpaper',
      'relationship',
      'playback',
      'movie',
      'movie_playback'
    )
  ),
  item_id text not null,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (couple_code, data_type, item_id)
);

create index if not exists couple_app_data_couple_created_idx
  on public.couple_app_data (couple_code, created_at);

create or replace function public.is_heartlink_couple_member(target_couple_code text)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.couples
    where couples.couple_code = target_couple_code
      and (
        lower(couples.user1_email) = lower(auth.jwt() ->> 'email')
        or lower(couples.user2_email) = lower(auth.jwt() ->> 'email')
      )
  );
$$;

revoke all on function public.is_heartlink_couple_member(text) from public;
grant execute on function public.is_heartlink_couple_member(text) to authenticated;

alter table public.couple_app_data enable row level security;

grant select, insert, update, delete on public.couple_app_data to authenticated;
grant usage, select on sequence public.couple_app_data_id_seq to authenticated;

drop policy if exists "Couple members can read app data" on public.couple_app_data;
create policy "Couple members can read app data"
  on public.couple_app_data for select to authenticated
  using (public.is_heartlink_couple_member(couple_code));

drop policy if exists "Couple members can add app data" on public.couple_app_data;
create policy "Couple members can add app data"
  on public.couple_app_data for insert to authenticated
  with check (public.is_heartlink_couple_member(couple_code));

drop policy if exists "Couple members can update app data" on public.couple_app_data;
create policy "Couple members can update app data"
  on public.couple_app_data for update to authenticated
  using (public.is_heartlink_couple_member(couple_code))
  with check (public.is_heartlink_couple_member(couple_code));

drop policy if exists "Couple members can delete app data" on public.couple_app_data;
create policy "Couple members can delete app data"
  on public.couple_app_data for delete to authenticated
  using (public.is_heartlink_couple_member(couple_code));

